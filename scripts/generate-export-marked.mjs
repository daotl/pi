import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { posix } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build, version as esbuildVersion } from "esbuild";

// This local backport belongs to Marked's tokenizer, not the viewer. Revisit it
// when upgrading Marked; never silently apply it to different upstream sources.
const MARKED_VERSION = "18.0.11";
const ESBUILD_VERSION = "0.28.2";
const SOURCE_MAP_SHA256 = "2140b1d34433b175421ca86d8d847e429a48556cc40be7b853e45d697699335a";
const require = createRequire(import.meta.url);
const markedPackage = require.resolve("marked/package.json");
const packageUrl = pathToFileURL(markedPackage);
const metadata = JSON.parse(await readFile(packageUrl, "utf8"));
if (metadata.version !== MARKED_VERSION || esbuildVersion !== ESBUILD_VERSION) {
	throw new Error(`Expected marked ${MARKED_VERSION} and esbuild ${ESBUILD_VERSION}; got ${metadata.version} and ${esbuildVersion}`);
}
const sourceMapBytes = await readFile(new URL("lib/marked.esm.js.map", packageUrl));
if (createHash("sha256").update(sourceMapBytes).digest("hex") !== SOURCE_MAP_SHA256) {
	throw new Error("Pinned Marked source map changed; review upstream sources before regenerating");
}
const sourceMap = JSON.parse(sourceMapBytes.toString("utf8"));
const sources = new Map();
for (let index = 0; index < sourceMap.sources.length; index++) {
	const name = sourceMap.sources[index];
	const source = sourceMap.sourcesContent[index];
	if (!/^\.\.\/src\/[A-Za-z]+\.ts$/.test(name) || typeof source !== "string" || sources.has(name)) {
		throw new Error(`Unexpected Marked source map entry: ${name}`);
	}
	sources.set(name, source);
}

const original = `          for (let i = this.lexer.inlineQueue.length - 1; i >= 0; i--) {
            if (this.rules.other.listIsTask.test(this.lexer.inlineQueue[i].src)) {
              this.lexer.inlineQueue[i].src = this.lexer.inlineQueue[i].src.replace(this.rules.other.listReplaceTask, '');
              break;
            }
          }`;
const replacement = `          // The two-pass list tokenizer has already queued later paragraphs.
          // Remove this item's marker only from its own inline token array.
          const inlineEntry = this.lexer.inlineQueue.find(entry => entry.tokens === itemToken.tokens);
          if (inlineEntry) {
            inlineEntry.src = inlineEntry.src.replace(this.rules.other.listReplaceTask, '');
          }`;
const tokenizer = sources.get("../src/Tokenizer.ts");
if (!tokenizer || tokenizer.split(original).length !== 2) {
	throw new Error("Expected exactly one task-list queue repair site in pinned Tokenizer.ts");
}
sources.set("../src/Tokenizer.ts", tokenizer.replace(original, replacement));

// Bundle the readable TypeScript from the authenticated source map in memory.
// No generated/minified source replacement, temp files, or dependency writes.
const bundled = await build({
	entryPoints: ["../src/marked.ts"],
	bundle: true,
	format: "cjs",
	platform: "browser",
	target: "es2022",
	minify: true,
	charset: "utf8",
	legalComments: "none",
	write: false,
	plugins: [{
		name: "pinned-marked-sources",
		setup(builder) {
			builder.onResolve({ filter: /.*/ }, (args) => {
				const name = args.kind === "entry-point"
					? args.path
					: posix.normalize(posix.join(posix.dirname(args.importer), args.path));
				if (!sources.has(name)) throw new Error(`Unexpected Marked runtime import: ${name}`);
				return { path: name, namespace: "marked-source" };
			});
			builder.onLoad({ filter: /.*/, namespace: "marked-source" }, (args) => ({
				contents: sources.get(args.path),
				loader: "ts",
			}));
		},
	}],
});
if (bundled.outputFiles.length !== 1) throw new Error("Expected one bundled Marked output");
const license = await readFile(new URL("LICENSE", packageUrl), "utf8");
if (license.includes("*/")) throw new Error("Unexpected comment terminator in Marked license");
const header = `/**
 * marked v${MARKED_VERSION} - a markdown parser
 * https://github.com/markedjs/marked
 * Generated by node scripts/generate-export-marked.mjs; DO NOT EDIT.
 * Source: marked@${MARKED_VERSION}/lib/marked.esm.js.map
 * Source SHA-256: ${SOURCE_MAP_SHA256}
 * Local backport: associate task marker removal with its paragraph's tokens.
 * Bundler: esbuild@${ESBUILD_VERSION}, browser/CJS, ES2022, minified UTF-8.
 *
${license.trimEnd().split("\n").map((line) => line ? ` * ${line}` : " *").join("\n")}
 */
`;
// Preserve Marked's browser-global, CommonJS and AMD entry-point contracts.
const prefix = `(function(g,f){if(typeof exports==="object"&&typeof module!=="undefined"){module.exports=f()}else if(typeof define==="function"&&define.amd){define("marked",f)}else{g.marked=f()}})(typeof globalThis!=="undefined"?globalThis:typeof self!=="undefined"?self:this,function(){var exports={};var module={exports};\n`;
const output = header + prefix + bundled.outputFiles[0].text + "\nreturn module.exports;});\n";
const destination = new URL("../packages/coding-agent/src/core/export-html/vendor/marked.min.js", import.meta.url);
if (process.argv.length > 3 || (process.argv[2] !== undefined && process.argv[2] !== "--check")) {
	throw new Error("Usage: node scripts/generate-export-marked.mjs [--check]");
}
if (process.argv[2] === "--check") {
	if (await readFile(destination, "utf8") !== output) {
		throw new Error("Vendored Marked is stale; run node scripts/generate-export-marked.mjs");
	}
} else {
	await writeFile(destination, output);
	console.log(`Generated ${fileURLToPath(destination)}`);
}
